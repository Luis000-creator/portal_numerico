-- =========================================================
-- PORTAL NUMÉRICO - BASE DE DATOS DE APUNTES
-- Supabase / PostgreSQL
--
-- Ejecutar UNA SOLA VEZ desde:
-- Supabase > SQL Editor
-- =========================================================


-- 1. CREAR TABLA DE APUNTES
create table if not exists public.apuntes (
                                              id bigint generated by default as identity primary key,

                                              titulo text not null
                                              check (char_length(titulo) between 1 and 200),

    contenido text not null
    check (char_length(contenido) between 1 and 20000),

    created_at timestamptz not null default now()
    );


-- 2. ACTIVAR ROW LEVEL SECURITY (RLS)
alter table public.apuntes enable row level security;


-- =========================================================
-- POLÍTICA DE LECTURA
-- Todos los visitantes de la página pueden ver los apuntes.
-- =========================================================

drop policy if exists "apuntes_select_public"
on public.apuntes;

create policy "apuntes_select_public"
on public.apuntes
for select
                    to anon, authenticated
                    using (true);


-- =========================================================
-- POLÍTICA DE PUBLICACIÓN
-- Cualquier persona que tenga acceso a la página puede
-- publicar un apunte.
-- =========================================================

drop policy if exists "apuntes_insert_public"
on public.apuntes;

create policy "apuntes_insert_public"
on public.apuntes
for insert
to anon, authenticated
with check (true);


-- =========================================================
-- 3. COLUMNA PARA ARCHIVO ADJUNTO (PDF / Markdown)
-- =========================================================

alter table public.apuntes
add column if not exists archivo_url text;


-- =========================================================
-- 4. BUCKET DE STORAGE PARA ARCHIVOS DE APUNTES
-- Bucket publico: los archivos se sirven por URL publica.
-- =========================================================

insert into storage.buckets (id, name, public)
values ('archivos_apuntes', 'archivos_apuntes', true)
on conflict (id) do nothing;


-- =========================================================
-- POLITICAS DE STORAGE
-- Todos los visitantes pueden leer y subir archivos,
-- igual que con los apuntes (portal colaborativo de clase).
-- =========================================================

drop policy if exists "Archivos publicos"
on storage.objects;

create policy "Archivos publicos"
on storage.objects
for select
to anon, authenticated
using (bucket_id = 'archivos_apuntes');

drop policy if exists "Subir archivos"
on storage.objects;

create policy "Subir archivos"
on storage.objects
for insert
to anon, authenticated
with check (bucket_id = 'archivos_apuntes');


-- =========================================================
-- 5. LÍMITES SIN LOGIN (12-nov)
-- SELECT/INSERT siguen públicos (no hay login por decisión del equipo),
-- pero la base acota lo que se puede escribir: nada de URLs en el título
-- y archivo_url apuntando solo al bucket propio del portal. El cliente
-- (js/apuntes.js) valida lo mismo; el CHECK es la garantía real, porque
-- no depende del JavaScript del navegador.
-- =========================================================

alter table public.apuntes
    drop constraint if exists apuntes_titulo_sin_url;

alter table public.apuntes
    add constraint apuntes_titulo_sin_url
        check (titulo !~* 'https?://|www\.');

alter table public.apuntes
    drop constraint if exists apuntes_archivo_url_bloque;

alter table public.apuntes
    add constraint apuntes_archivo_url_bloque
        check (archivo_url is null
            or archivo_url like 'https://ekmgyckzxhuiyzlncryw.supabase.co/storage/v1/object/public/archivos_apuntes/%');


-- =========================================================
-- 6. BORRAR DUPLICADOS (12-nov)
-- EJERCICIO_7: ids 32 y 33 (33 = versión corregida).
-- EJERCICIO_6_PF: ids 45 y 47 (archivos idénticos).
-- La página ya deduplica al mostrar, pero las filas siguen en la BD
-- y RLS no permite DELETE público: este borrado se hace desde el
-- panel de Supabase (SQL Editor).
-- =========================================================
delete from public.apuntes where id in (32, 45);


-- =========================================================
-- IMPORTANTE
--
-- NO damos permisos UPDATE ni DELETE públicamente.
--
-- Esto significa:
--
-- ✔ Todos pueden ver apuntes.
-- ✔ Todos pueden publicar apuntes.
-- ✘ Los visitantes no pueden modificar apuntes existentes.
-- ✘ Los visitantes no pueden borrar apuntes.
--
-- Si necesitas borrar algo, puedes hacerlo desde
-- el panel de Supabase.
